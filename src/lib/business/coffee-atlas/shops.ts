export function getCoffeeAtlasShop(slug: string): CoffeeAtlasShop | null {
  return COFFEE_ATLAS_SHOPS.find((shop) => shop.slug === slug) ?? null;
}

/** Previous / next shop; the route loops (10 → 1) so the journey never dead-ends. */
export function getCoffeeAtlasNeighbours(slug: string): {
  previous: CoffeeAtlasShop;
  next: CoffeeAtlasShop;
} | null {
  const index = COFFEE_ATLAS_SHOPS.findIndex((shop) => shop.slug === slug);
  if (index < 0) {
    return null;
  }
  const count = COFFEE_ATLAS_SHOPS.length;
  return {
    previous: COFFEE_ATLAS_SHOPS[(index - 1 + count) % count],
    next: COFFEE_ATLAS_SHOPS[(index + 1) % count],
  };
}

