DECLARE
  v_sprint_id uuid;
  v_total integer;
  v_music integer;
  v_voice integer;
  v_group_conflicts integer;
BEGIN
  SELECT id INTO v_sprint_id
  FROM public.seo_sprints
  WHERE slug = 'vkus-zhizni-2026';

  IF v_sprint_id IS NULL THEN
    RAISE EXCEPTION 'seo_sprint_vkus_zhizni_not_found';
  END IF;

  SELECT
    count(*),
    count(*) FILTER (WHERE author_group = 'music'),
    count(*) FILTER (WHERE author_group = 'voice')
  INTO v_total, v_music, v_voice
  FROM public.seo_sprint_queries
  WHERE sprint_id = v_sprint_id AND pool = 'initial';

  IF v_total <> 266 OR v_music <> 140 OR v_voice <> 126 THEN
    RAISE EXCEPTION
      'seo_sprint_vkus_zhizni_seed_count_mismatch total=% music=% voice=%',
      v_total, v_music, v_voice;
  END IF;

  -- A query shared with another sprint must keep one author_group, otherwise the
  -- title lock lookup fails closed for it.
  SELECT count(*) INTO v_group_conflicts
  FROM public.seo_sprint_queries AS mine
  JOIN public.seo_sprint_queries AS other
    ON other.query_id = mine.query_id AND other.sprint_id <> mine.sprint_id
  WHERE mine.sprint_id = v_sprint_id
    AND other.released_to_general_at IS NULL
    AND other.author_group <> mine.author_group;

  IF v_group_conflicts <> 0 THEN
    RAISE EXCEPTION 'seo_sprint_vkus_zhizni_group_conflicts=%', v_group_conflicts;
  END IF;
END;
$$;

