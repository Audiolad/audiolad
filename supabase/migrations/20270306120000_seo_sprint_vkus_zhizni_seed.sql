SELECT
  sprint.id,
  query_row.id,
  seed.display_title,
  seed.author_group,
  seed.pool
FROM seed
CROSS JOIN sprint
JOIN public.seo_queries AS query_row
  ON query_row.normalized_query = public.normalize_seo_query(seed.display_title)
ON CONFLICT (sprint_id, query_id) DO UPDATE SET
  display_title = EXCLUDED.display_title,
  author_group = EXCLUDED.author_group,
  pool = EXCLUDED.pool;

-- Product titles are locked to query_text, so the first letter is capitalised for this
-- sprint's queries (same rule as 20261220124000). Only the first character changes,
-- normalized_query stays equal. Rows already linked to a product are left as they are.
UPDATE public.seo_queries AS q
SET query_text = upper(left(q.query_text, 1)) || substr(q.query_text, 2)
FROM public.seo_sprint_queries AS sq
JOIN public.seo_sprints AS s ON s.id = sq.sprint_id AND s.slug = 'vkus-zhizni-2026'
WHERE sq.query_id = q.id
  AND left(q.query_text, 1) <> upper(left(q.query_text, 1))
  AND NOT EXISTS (
    SELECT 1 FROM public.practices AS p WHERE p.primary_seo_query_id = q.id
  )
  AND NOT EXISTS (
    SELECT 1
    FROM public.seo_sprint_queries AS other_sq
    JOIN public.seo_sprints AS other_s ON other_s.id = other_sq.sprint_id
    WHERE other_sq.query_id = q.id AND other_s.slug <> 'vkus-zhizni-2026'
  );

