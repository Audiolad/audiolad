-- 5. The single price source per business account.
-- source: 'entitlement' (bound, personal price left), 'finished' (all personal periods used),
-- 'reserved' (code held by this owner, first payment not made yet) or 'standard'.
CREATE FUNCTION public.business_partner_quote_internal(p_organization_id uuid, p_user_id uuid)
RETURNS TABLE (source text, unit_price_minor bigint, code_id uuid, period_index integer,
  discount_periods integer, periods_used integer)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_e public.business_partner_entitlements%ROWTYPE; v_c public.business_partner_codes%ROWTYPE; v_used integer;
BEGIN
  IF p_organization_id IS NOT NULL THEN
    SELECT * INTO v_e FROM public.business_partner_entitlements e WHERE e.organization_id = p_organization_id;
    IF FOUND THEN
      SELECT count(*) INTO v_used FROM public.business_partner_entitlement_periods p WHERE p.organization_id = p_organization_id;
      IF v_used < v_e.discount_periods THEN
        RETURN QUERY SELECT 'entitlement'::text, v_e.unit_price_minor, v_e.code_id, v_used + 1, v_e.discount_periods::integer, v_used;
      ELSE
        RETURN QUERY SELECT 'finished'::text, 79900::bigint, v_e.code_id, NULL::integer, v_e.discount_periods::integer, v_used;
      END IF;
      RETURN;
    END IF;
  END IF;
  IF p_user_id IS NOT NULL THEN
    SELECT c.* INTO v_c FROM public.business_partner_codes c
    WHERE c.reserved_by_user_id = p_user_id AND c.bound_organization_id IS NULL AND c.revoked_at IS NULL
      AND (c.reserved_until > clock_timestamp() OR EXISTS (
        SELECT 1 FROM public.business_subscription_order_scopes s JOIN public.orders o ON o.id = s.order_id
        WHERE s.partner_code_id = c.id AND o.user_id = p_user_id AND o.status = 'pending'))
    ORDER BY c.reserved_until DESC LIMIT 1;
    IF FOUND THEN
      RETURN QUERY SELECT 'reserved'::text, v_c.unit_price_minor, v_c.id, 1, v_c.discount_periods::integer, 0;
      RETURN;
    END IF;
  END IF;
  RETURN QUERY SELECT 'standard'::text, 79900::bigint, NULL::uuid, NULL::integer, NULL::integer, 0;
END; $$;
REVOKE ALL ON FUNCTION public.business_partner_quote_internal(uuid, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.business_partner_quote_internal(uuid, uuid) TO service_role;

-- Owner organization of the caller, the same selection as the checkout.
