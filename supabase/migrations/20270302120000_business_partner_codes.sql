-- 1. The code: issue, uniqueness, purpose, one-time redemption.
CREATE TABLE public.business_partner_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Normalized (no dashes), 12 chars from an alphabet without 0/1/I/O. Generated by the server.
  code text NOT NULL UNIQUE CHECK (code ~ '^[2-9A-HJ-NP-Z]{12}$'),
  purpose text NOT NULL CHECK (purpose IN ('custdev', 'top10', 'other')),
  recipient_note text NULL CHECK (recipient_note IS NULL OR char_length(recipient_note) <= 200),
  -- Whole rubles only, strictly below the standard price.
  unit_price_minor bigint NOT NULL DEFAULT 39900
    CHECK (unit_price_minor BETWEEN 100 AND 79800 AND unit_price_minor % 100 = 0),
  discount_periods smallint NOT NULL DEFAULT 3 CHECK (discount_periods BETWEEN 1 AND 12),
  created_by uuid NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  -- Short reservation by one owner account between entering the code and the first payment.
  reserved_by_user_id uuid NULL,
  reserved_until timestamptz NULL,
  -- Set once, on the first successful real payment. Never cleared.
  bound_organization_id uuid NULL,
  bound_at timestamptz NULL,
  revoked_at timestamptz NULL,
  CONSTRAINT business_partner_codes_bound_pair CHECK ((bound_organization_id IS NULL) = (bound_at IS NULL)),
  CONSTRAINT business_partner_codes_reserved_pair CHECK ((reserved_by_user_id IS NULL) = (reserved_until IS NULL))
);
CREATE UNIQUE INDEX business_partner_codes_one_per_organization
  ON public.business_partner_codes(bound_organization_id) WHERE bound_organization_id IS NOT NULL;
CREATE INDEX business_partner_codes_reserved_by ON public.business_partner_codes(reserved_by_user_id)
  WHERE reserved_by_user_id IS NOT NULL;
ALTER TABLE public.business_partner_codes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.business_partner_codes FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.business_partner_codes TO service_role;
COMMENT ON TABLE public.business_partner_codes IS
  'Personal one-time partner codes (task 8142d69a). Service role only. A code binds to one business organization on its first successful payment.';

