-- 7. Binding and period history, called only from apply_business_subscription_for_order
-- after a succeeded real payment. Idempotent per order.
CREATE FUNCTION public.business_partner_apply_period_internal(
  p_order_id uuid, p_organization_id uuid, p_code_id uuid, p_unit_price_minor bigint,
  p_venue_count integer, p_period_start timestamptz, p_period_end timestamptz, p_paid_at timestamptz
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_c public.business_partner_codes%ROWTYPE; v_e public.business_partner_entitlements%ROWTYPE; v_used integer;
BEGIN
  IF EXISTS (SELECT 1 FROM public.business_partner_entitlement_periods WHERE order_id = p_order_id) THEN
    RETURN jsonb_build_object('recorded', false, 'already', true);
  END IF;
  SELECT * INTO v_c FROM public.business_partner_codes WHERE id = p_code_id FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('recorded', false, 'reason', 'code_missing'); END IF;
  SELECT * INTO v_e FROM public.business_partner_entitlements WHERE organization_id = p_organization_id FOR UPDATE;
  IF NOT FOUND THEN
    IF v_c.revoked_at IS NOT NULL THEN
      -- Revoked before its first payment: the money was charged at the shown price and buys
      -- this one paid period; the code never binds and no personal price follows.
      INSERT INTO public.business_subscription_superseded_orders(order_id, organization_id, reason, late_paid_at)
      VALUES (p_order_id, p_organization_id, 'partner_code_revoked', p_paid_at)
      ON CONFLICT (order_id) DO UPDATE SET late_paid_at = coalesce(
        public.business_subscription_superseded_orders.late_paid_at, EXCLUDED.late_paid_at);
      RETURN jsonb_build_object('recorded', false, 'reason', 'code_revoked');
    END IF;
    IF v_c.bound_organization_id IS NOT NULL AND v_c.bound_organization_id <> p_organization_id THEN
      -- The paid amount was confirmed and charged; access stays. The code is not moved.
      RETURN jsonb_build_object('recorded', false, 'reason', 'code_bound_elsewhere');
    END IF;
    UPDATE public.business_partner_codes
    SET bound_organization_id = p_organization_id, bound_at = p_paid_at, reserved_by_user_id = NULL, reserved_until = NULL
    WHERE id = v_c.id;
    INSERT INTO public.business_partner_entitlements(organization_id, code_id, unit_price_minor, discount_periods, first_paid_at)
    VALUES (p_organization_id, v_c.id, v_c.unit_price_minor, v_c.discount_periods, p_paid_at)
    RETURNING * INTO v_e;
  ELSIF v_e.code_id <> p_code_id THEN
    RETURN jsonb_build_object('recorded', false, 'reason', 'other_code');
  END IF;
  SELECT count(*) INTO v_used FROM public.business_partner_entitlement_periods WHERE organization_id = p_organization_id;
  IF v_used >= v_e.discount_periods THEN
    RETURN jsonb_build_object('recorded', false, 'reason', 'window_full');
  END IF;
  INSERT INTO public.business_partner_entitlement_periods(order_id, organization_id, period_index, unit_price_minor,
    venue_count, period_start, period_end)
  VALUES (p_order_id, p_organization_id, v_used + 1, p_unit_price_minor, p_venue_count, p_period_start, p_period_end);
  RETURN jsonb_build_object('recorded', true, 'period_index', v_used + 1, 'discount_periods', v_e.discount_periods);
END; $$;
REVOKE ALL ON FUNCTION public.business_partner_apply_period_internal(uuid, uuid, uuid, bigint, integer, timestamptz, timestamptz, timestamptz)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.business_partner_apply_period_internal(uuid, uuid, uuid, bigint, integer, timestamptz, timestamptz, timestamptz)
  TO service_role;

-- Admin revoke: only a code not bound to an account. Its open personal-price links stop
-- being offered at once; a late payment on one is handled by business_partner_apply_period_internal.
CREATE FUNCTION public.revoke_business_partner_code(p_code_id uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_c public.business_partner_codes%ROWTYPE; v_n integer;
BEGIN
  SELECT * INTO v_c FROM public.business_partner_codes WHERE id = p_code_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'partner_code_invalid' USING ERRCODE = 'P0001'; END IF;
  IF v_c.bound_organization_id IS NOT NULL THEN RAISE EXCEPTION 'partner_code_bound' USING ERRCODE = 'P0001'; END IF;
  UPDATE public.business_partner_codes
  SET revoked_at = coalesce(revoked_at, clock_timestamp()), reserved_by_user_id = NULL, reserved_until = NULL
  WHERE id = v_c.id;
  INSERT INTO public.business_subscription_superseded_orders(order_id, organization_id, reason)
  SELECT s.order_id, s.organization_id, 'partner_code_revoked'
  FROM public.business_subscription_order_scopes s JOIN public.orders o ON o.id = s.order_id
  WHERE s.partner_code_id = v_c.id AND o.status = 'pending'
  ON CONFLICT (order_id) DO NOTHING;
  -- Cancelled so the owner gets a fresh ordinary link; a late bank confirmation is still fulfilled.
  UPDATE public.orders o SET status = 'cancelled', cancelled_at = clock_timestamp(), updated_at = clock_timestamp()
  FROM public.business_subscription_order_scopes s
  WHERE s.order_id = o.id AND s.partner_code_id = v_c.id AND o.status = 'pending';
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN jsonb_build_object('ok', true, 'already', v_c.revoked_at IS NOT NULL, 'invalidated_orders', v_n);
END; $$;
REVOKE ALL ON FUNCTION public.revoke_business_partner_code(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.revoke_business_partner_code(uuid) TO service_role;

-- 8. Guards use the same price source as the checkout.
CREATE OR REPLACE FUNCTION public.business_subscription_scope_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_q record; v_user uuid;
BEGIN
  IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'subscription_scope_immutable' USING ERRCODE='42501'; END IF;
  SELECT o.user_id INTO v_user FROM public.orders o WHERE o.id = NEW.order_id;
  SELECT * INTO v_q FROM public.business_partner_quote_internal(NEW.organization_id, v_user);
  IF cardinality(NEW.location_ids)<>(SELECT count(DISTINCT x) FROM unnest(NEW.location_ids) x)
  OR EXISTS (SELECT 1 FROM unnest(NEW.location_ids) x WHERE NOT EXISTS (
    SELECT 1 FROM public.business_locations l WHERE l.id=x AND l.organization_id=NEW.organization_id AND l.status='active'))
  OR NEW.unit_price_minor IS DISTINCT FROM v_q.unit_price_minor
  OR (NEW.partner_code_id IS NOT NULL AND (NEW.partner_code_id IS DISTINCT FROM v_q.code_id
      OR NEW.partner_period_index IS DISTINCT FROM v_q.period_index))
  OR NOT EXISTS (SELECT 1 FROM public.orders o JOIN public.business_organization_members m ON m.user_id=o.user_id
    WHERE o.id=NEW.order_id AND o.order_kind='business_subscription' AND o.status='pending'
    AND o.amount_minor=NEW.unit_price_minor*cardinality(NEW.location_ids) AND o.currency='RUB'
    AND m.organization_id=NEW.organization_id AND m.role='owner') THEN
    RAISE EXCEPTION 'subscription_scope_mismatch' USING ERRCODE='42501';
  END IF;
  RETURN NEW;
END; $$;

CREATE OR REPLACE FUNCTION public.business_pilot_order_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_org uuid; v_count integer; v_unit bigint;
BEGIN
  IF NEW.order_kind='business_subscription' AND NEW.status='pending' THEN
    SELECT o.id INTO v_org FROM public.business_organization_members m JOIN public.business_organizations o ON o.id=m.organization_id
    WHERE m.user_id=NEW.user_id AND m.role='owner' AND o.status='active'
    ORDER BY m.created_at,o.id LIMIT 1;
    IF v_org IS NOT NULL THEN
      SELECT count(*) INTO v_count FROM public.business_locations WHERE organization_id=v_org AND status='active';
      SELECT q.unit_price_minor INTO v_unit FROM public.business_partner_quote_internal(v_org, NEW.user_id) q;
      IF v_count >= 1 AND (v_count > public.business_venue_slot_limit_internal(v_org)
        OR NEW.amount_minor IS DISTINCT FROM coalesce(v_unit, 79900)*v_count OR NEW.currency IS DISTINCT FROM 'RUB') THEN
        RAISE EXCEPTION 'subscription_amount_mismatch' USING ERRCODE='42501';
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END; $$;

-- 9. Checkout. The two-argument form is the one the cabinet calls: the owner confirms the
-- per-venue price he saw. The old one-argument form stays for compatibility and only
-- creates an order at the standard price.
CREATE FUNCTION public.create_business_subscription_order(
  p_idempotency_key uuid,
  p_expected_unit_price_minor bigint
)
RETURNS TABLE (
  order_id uuid,
  status text,
  amount_minor bigint,
  currency text,
  order_kind text,
  created_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_existing public.orders%ROWTYPE;
  v_new_order public.orders%ROWTYPE;
  v_key text;
  v_org uuid; v_locations uuid[]; v_pilot boolean := false; v_amount bigint := 79900;
  v_quote record; v_unit bigint := 79900; v_q_code uuid; v_q_index integer;
  v_xscope public.business_subscription_order_scopes%ROWTYPE; v_replace_reason text;
BEGIN
  IF public.business_consent_caller_in_support_mode() THEN
    RAISE EXCEPTION 'support_mode_consent_forbidden' USING ERRCODE = '42501';
  END IF;

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
  END IF;

  IF p_idempotency_key IS NULL THEN
    RAISE EXCEPTION 'idempotency_key_required' USING ERRCODE = '22023';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.business_organization_members AS m
    WHERE m.user_id = v_user_id
      AND m.role = 'owner'
  ) THEN
    RAISE EXCEPTION 'not_organization_owner'
      USING ERRCODE = '42501',
            HINT = 'https://business.audiolad.ru/onboarding';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.business_offer_acceptances AS a
    WHERE a.user_id = v_user_id
  ) THEN
    RAISE EXCEPTION 'offer_acceptance_required'
      USING ERRCODE = 'P0001',
            HINT = 'https://business.audiolad.ru/documents/b2b-terms';
  END IF;

  -- Same organization lock as activation; count only physical active venues.
  -- Every organization uses the same rule; no per-client flag is needed.
  SELECT o.id INTO v_org
  FROM public.business_organization_members m JOIN public.business_organizations o ON o.id=m.organization_id
  WHERE m.user_id=v_user_id AND m.role='owner' AND o.status='active'
  ORDER BY m.created_at, o.id LIMIT 1 FOR UPDATE OF o;
  IF v_org IS NOT NULL THEN
    SELECT array_agg(l.id ORDER BY l.id) INTO v_locations FROM public.business_locations l
    WHERE l.organization_id=v_org AND l.status='active';
    -- Without an active Location the old single 79900 order path stays unchanged.
    v_pilot := coalesce(cardinality(v_locations),0) >= 1;
  END IF;
  IF v_pilot THEN
    IF cardinality(v_locations) > public.business_venue_slot_limit_internal(v_org) THEN
      RAISE EXCEPTION 'invalid_active_location_count' USING ERRCODE='22023';
    END IF;
    -- One price per account, the same for every active venue: the standard 79900 or the
    -- confirmed personal partner price. Computed here, never taken from the client.
    -- The code row this owner holds is locked first, so a reservation cannot change hands
    -- between reading the price and opening the payment link.
    PERFORM 1 FROM public.business_partner_codes c
    WHERE c.reserved_by_user_id = v_user_id AND c.bound_organization_id IS NULL
    ORDER BY c.id FOR UPDATE;
    SELECT * INTO v_quote FROM public.business_partner_quote_internal(v_org, v_user_id);
    v_unit := coalesce(v_quote.unit_price_minor, 79900);
    v_q_code := v_quote.code_id; v_q_index := v_quote.period_index;
    v_amount := v_unit * cardinality(v_locations);
    -- No mid-period charge for adding a venue. Renewal can include it after expiry.
    IF EXISTS (SELECT 1 FROM unnest(v_locations) AS v(id)
      WHERE public.business_venue_paid_until(v_org, v.id) > clock_timestamp())
    AND EXISTS (SELECT 1 FROM unnest(v_locations) AS v(id)
      WHERE coalesce(public.business_venue_paid_until(v_org, v.id) <= clock_timestamp(), true)
    ) THEN RAISE EXCEPTION 'venue_topup_not_available' USING ERRCODE='P0001'; END IF;
  END IF;

  -- The caller must have seen exactly this per-venue price before the payment link exists.
  IF v_unit IS DISTINCT FROM coalesce(p_expected_unit_price_minor, 79900) THEN
    RAISE EXCEPTION 'partner_terms_changed' USING ERRCODE = 'P0001';
  END IF;

  v_key := p_idempotency_key::text;
  PERFORM pg_advisory_xact_lock(hashtextextended('business_subscription_order:' || v_user_id::text, 0));

  SELECT o.*
  INTO v_existing
  FROM public.orders AS o
  WHERE o.idempotency_key = v_key;

  IF FOUND THEN
    IF v_existing.user_id IS DISTINCT FROM v_user_id
       OR v_existing.order_kind IS DISTINCT FROM 'business_subscription'
       OR v_existing.amount_minor IS DISTINCT FROM v_amount THEN
      RAISE EXCEPTION 'idempotency_key_conflict' USING ERRCODE = '23505';
    END IF;
    IF coalesce(v_pilot,false) AND NOT EXISTS (
      SELECT 1 FROM public.business_subscription_order_scopes s WHERE s.order_id=v_existing.id
      AND s.organization_id=v_org AND s.location_ids=v_locations
    ) THEN RAISE EXCEPTION 'pending_order_mismatch' USING ERRCODE='P0001'; END IF;
    order_id := v_existing.id;
    status := v_existing.status;
    amount_minor := v_existing.amount_minor;
    currency := v_existing.currency;
    order_kind := v_existing.order_kind;
    created_at := v_existing.created_at;
    RETURN NEXT;
    RETURN;
  END IF;

  -- Two owners of one account: only one open link for the same personal-price period.
  IF v_unit <> 79900 AND EXISTS (
    SELECT 1 FROM public.business_subscription_order_scopes s JOIN public.orders o ON o.id = s.order_id
    WHERE s.organization_id = v_org AND s.partner_code_id = v_q_code
      AND s.partner_period_index = v_q_index AND o.status = 'pending' AND o.user_id <> v_user_id
      AND o.created_at > clock_timestamp() - interval '72 hours'
      AND NOT EXISTS (SELECT 1 FROM public.business_subscription_superseded_orders x WHERE x.order_id = o.id)) THEN
    RAISE EXCEPTION 'partner_period_in_payment' USING ERRCODE = 'P0001';
  END IF;

  -- At most one open link per owner (orders_one_pending_business_subscription_per_user_idx).
  SELECT o.*
  INTO v_existing
  FROM public.orders AS o
  WHERE o.user_id = v_user_id
    AND o.order_kind = 'business_subscription'
    AND o.status = 'pending'
  ORDER BY o.created_at ASC
  LIMIT 1
  FOR UPDATE;

  -- The owner's own unpaid link that no longer matches is replaced, never a dead end:
  -- an ordinary or same-code link when a code price applies now, or a link of a revoked code.
  -- It is cancelled so that the new link can exist; a late bank confirmation of it is still
  -- fulfilled (fulfill_tochka_payment_transactional) and buys exactly the 30 days it paid for.
  -- Without a code nothing changes for the ordinary owner.
  IF v_existing.id IS NOT NULL THEN
    SELECT s.* INTO v_xscope FROM public.business_subscription_order_scopes s WHERE s.order_id = v_existing.id;
    IF NOT (v_existing.amount_minor = v_amount AND v_existing.currency = 'RUB' AND (NOT coalesce(v_pilot, false)
        OR (v_xscope.organization_id = v_org AND v_xscope.location_ids = v_locations AND v_xscope.unit_price_minor = v_unit))) THEN
      IF v_xscope.partner_code_id IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.business_partner_codes c WHERE c.id = v_xscope.partner_code_id AND c.revoked_at IS NOT NULL) THEN
        v_replace_reason := 'partner_code_revoked';
      ELSIF v_unit <> 79900 AND (v_xscope.partner_code_id IS NULL OR v_xscope.partner_code_id = v_q_code) THEN
        v_replace_reason := 'partner_code_applied';
      END IF;
      IF v_replace_reason IS NOT NULL THEN
        INSERT INTO public.business_subscription_superseded_orders(order_id, organization_id, reason)
        VALUES (v_existing.id, coalesce(v_xscope.organization_id, v_org), v_replace_reason)
        ON CONFLICT ON CONSTRAINT business_subscription_superseded_orders_pkey DO NOTHING;
        UPDATE public.orders SET status = 'cancelled', cancelled_at = clock_timestamp(), updated_at = clock_timestamp()
        WHERE id = v_existing.id;
        v_existing := NULL;
      END IF;
    END IF;
  END IF;

  IF v_existing.id IS NOT NULL THEN
    IF v_existing.amount_minor IS DISTINCT FROM v_amount
       OR v_existing.currency IS DISTINCT FROM 'RUB' THEN
      RAISE EXCEPTION 'pending_order_mismatch' USING ERRCODE = 'P0001';
    END IF;
    IF coalesce(v_pilot,false) AND NOT EXISTS (
      SELECT 1 FROM public.business_subscription_order_scopes s WHERE s.order_id=v_existing.id
      AND s.organization_id=v_org AND s.location_ids=v_locations
    ) THEN RAISE EXCEPTION 'pending_order_mismatch' USING ERRCODE='P0001'; END IF;
    order_id := v_existing.id;
    status := v_existing.status;
    amount_minor := v_existing.amount_minor;
    currency := v_existing.currency;
    order_kind := v_existing.order_kind;
    created_at := v_existing.created_at;
    RETURN NEXT;
    RETURN;
  END IF;

  INSERT INTO public.orders (
    user_id,
    practice_id,
    status,
    amount_minor,
    currency,
    practice_title_snapshot,
    practice_slug_snapshot,
    price_minor_snapshot,
    base_price_minor_snapshot,
    author_id_snapshot,
    idempotency_key,
    order_kind,
    target_access_level
  ) VALUES (
    v_user_id,
    NULL,
    'pending',
    v_amount,
    'RUB',
    'АудиоЛад Бизнес – доступ на 30 дней',
    'business-subscription',
    v_amount,
    v_amount,
    NULL,
    v_key,
    'business_subscription',
    NULL
  )
  RETURNING * INTO v_new_order;

  IF coalesce(v_pilot,false) THEN
    INSERT INTO public.business_subscription_order_scopes(order_id,organization_id,location_ids,
      unit_price_minor,partner_code_id,partner_period_index)
    VALUES(v_new_order.id,v_org,v_locations,v_unit,
      CASE WHEN v_unit <> 79900 THEN v_quote.code_id END,
      CASE WHEN v_unit <> 79900 THEN v_quote.period_index END);
    IF v_unit <> 79900 AND v_quote.source = 'reserved' THEN
      -- Keep the reservation while this payment link can still be paid.
      UPDATE public.business_partner_codes
      SET reserved_until = greatest(coalesce(reserved_until, clock_timestamp()), clock_timestamp() + interval '72 hours')
      WHERE id = v_quote.code_id AND bound_organization_id IS NULL AND reserved_by_user_id = v_user_id;
    END IF;
  END IF;
  order_id := v_new_order.id;
  status := v_new_order.status;
  amount_minor := v_new_order.amount_minor;
  currency := v_new_order.currency;
  order_kind := v_new_order.order_kind;
  created_at := v_new_order.created_at;
  RETURN NEXT;
END;
$$;

