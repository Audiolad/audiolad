  WHERE m.user_id = p_user_id AND m.role = 'owner' AND o.status = 'active'
  ORDER BY m.created_at, o.id LIMIT 1
$$;
REVOKE ALL ON FUNCTION public.business_partner_owner_organization(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.business_partner_owner_organization(uuid) TO service_role;

CREATE FUNCTION public.business_partner_quote_json(p_user_id uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_org uuid; v_q record; v_count integer := 0; v_hint text; v_until timestamptz;
BEGIN
  v_org := public.business_partner_owner_organization(p_user_id);
  IF v_org IS NOT NULL THEN
    SELECT count(*) INTO v_count FROM public.business_locations l WHERE l.organization_id = v_org AND l.status = 'active';
  END IF;
  SELECT * INTO v_q FROM public.business_partner_quote_internal(v_org, p_user_id);
  IF v_q.code_id IS NOT NULL THEN
    SELECT right(c.code, 4) INTO v_hint FROM public.business_partner_codes c WHERE c.id = v_q.code_id;
  END IF;
  IF v_org IS NOT NULL THEN
    SELECT max(p.period_end) INTO v_until FROM public.business_partner_entitlement_periods p WHERE p.organization_id = v_org;
  END IF;
  -- Without an active venue the old single-payment path stays at the standard price.
  IF v_count = 0 AND v_q.source = 'reserved' THEN
    v_q.unit_price_minor := 79900;
  END IF;
  RETURN jsonb_build_object(
    'source', v_q.source,
    'unit_price_minor', v_q.unit_price_minor,
    'standard_unit_price_minor', 79900,
    'venue_count', v_count,
    'total_minor', v_q.unit_price_minor * greatest(v_count, 1),
    'discount_periods', v_q.discount_periods,
    'period_index', v_q.period_index,
    'periods_used', v_q.periods_used,
    'code_hint', v_hint,
    'discount_paid_until', v_until);
END; $$;
REVOKE ALL ON FUNCTION public.business_partner_quote_json(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.business_partner_quote_json(uuid) TO service_role;

